from src.rag.ollama_client import (
    OllamaClient,
    OllamaClientError,
    OllamaConnectionError,
    OllamaModelNotFoundError,
    OllamaTimeoutError,
)

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Response schemas
# ---------------------------------------------------------------------------

class SourceCitation(BaseModel):
    """A citation pointing back to the source investigation."""

    investigation_id: str
    title: str
    relevant_text: str
    url: str | None = None
    doi: str | None = None
    active_version: int | None = None
    source_field: str | None = None


class AssistantResponse(BaseModel):
    """Complete response produced by the research assistant."""

    question: str
    answer: str
    confidence: str = Field(
        ...,
        description="Confidence level: high, medium, low, or insufficient_evidence.",
    )
    sources: list[SourceCitation]
    retrieved_chunks: list[RetrievalResult]
    disclaimer: str | None = Field(
        default=None,
        description="Added when evidence is weak, citations are rejected, or fallback occurred.",
    )
    llm_generated: bool = Field(
        default=False,
        description="True if generated by an active LLM, False if produced by template engine.",
    )
    model_name: str | None = Field(
        default=None,
        description="Name of the model that generated the answer.",
    )
    validated_citations: list[str] = Field(
        default_factory=list,
        description="Investigation IDs cited by the LLM that were verified against retrieved evidence.",
    )
    rejected_citations: list[str] = Field(
        default_factory=list,
        description="Investigation IDs cited by the LLM that were NOT present in retrieved evidence.",
    )


class ComparisonResponse(BaseModel):
    """Side-by-side comparison of two investigations."""

    investigation_1: dict[str, Any]
    investigation_2: dict[str, Any]
    similarities: list[str]
    differences: list[str]
    shared_categories: list[str]
    unique_categories_1: list[str]
    unique_categories_2: list[str]
    recommendation: str


class CategorySummary(BaseModel):
    """Aggregated summary of all research in a category."""

    category: str
    investigation_count: int
    investigations: list[str]
    key_objectives: list[str]
    platforms_used: list[str]
    summary_text: str


class GapAnalysis(BaseModel):
    """Analysis of research coverage and potential gaps."""

    topic: str
    covered_areas: list[str]
    potential_gaps: list[str]
    suggested_research_directions: list[str]
    related_investigations: list[str]


# ---------------------------------------------------------------------------
# Question classifier
# ---------------------------------------------------------------------------

_QUESTION_PATTERNS: list[tuple[str, str]] = [
    (r"\bcompare\b|\bvs\.?\b|\bdifference\b|\bsimilar", "comparison"),
    (r"\bwhat\s+is\b|\bdefine\b|\bdescri", "definition"),
    (r"\bhow\b|\bmethod\b|\bprocess\b|\bprocedure\b|\btechnique", "how"),
    (r"\bwhy\b|\breason\b|\bcause\b|\bpurpose\b|\bmotivat", "why"),
    (r"\bwho\b|\bresearcher\b|\bscientist\b|\binvestigator\b|\bpi\b", "who"),
    (r"\blist\b|\benumerate\b|\bwhich\b|\bcategories\b|\btypes", "list"),
    (r"\bgap\b|\bmissing\b|\bunexplored\b|\bfuture\b|\bopportunit", "gap"),
    (r"\bsummar|\boverview\b|\bstatus\b|\bprogress", "summary"),
]


def _classify_question(question: str) -> str:
    """Classify a question into a coarse intent category."""
    q_lower = question.lower()
    for pattern, label in _QUESTION_PATTERNS:
        if re.search(pattern, q_lower):
            return label
    return "general"


