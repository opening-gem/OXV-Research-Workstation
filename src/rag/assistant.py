"""
Evidence-Grounded NASA Research Assistant for Flame in Freefall.

Combines semantic retrieval over NASA Physical Sciences Informatics (PSI) data
with Ollama LLM generation and deterministic template fallbacks.

Pipeline:
  1. Retrieve relevant investigation records & document chunks via InvestigationRetriever.
  2. Rank and select evidence.
  3. Format evidence blocks with stable [INVESTIGATION_ID] citations.
  4. Generate natural-language synthesis using Ollama (or fallback template engine).
  5. Validate all model-generated citations against retrieved source evidence.
  6. Return structured AssistantResponse with clickable citations and confidence metrics.
"""

from __future__ import annotations

import logging
import re
from collections import Counter, defaultdict
from typing import Any, Dict, List, Optional, Set, Tuple

from src.catalog.compat_pydantic import BaseModel, Field
from src.rag.chunker import DocumentChunk
