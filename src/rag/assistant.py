# Research assistant
# ---------------------------------------------------------------------------

class ResearchAssistant:
    """
    NASA Research Assistant — Retrieval-Augmented Generation with Ollama.

    Retrieves evidence from NASA combustion science archives, constructs grounded
    prompts with citations, validates LLM output, and falls back gracefully to
    deterministic research synthesis when offline.
    """

    # Confidence thresholds (on top retrieval score)
    _HIGH_THRESHOLD: float = 0.50
    _MEDIUM_THRESHOLD: float = 0.25

    DEFAULT_SYSTEM_PROMPT: str = (
        "You are the Orbital Experimentation Volumetric (OXV) research assistant, specializing in NASA "
        "microgravity combustion science and spacecraft fire safety.\n\n"
        "Your role is to help researchers and mission planners understand orbital "
        "combustion investigations, experimental telemetry, and terrestrial applications.\n\n"
        "Guidelines:\n"
        "- Base factual claims strictly on the provided research context.\n"
        "- Cite source investigation IDs using bracketed notation (e.g., [BASS-II], [ACME], [FLEX]).\n"
        "- Distinguish measured flight observations from stated objectives or proposed applications.\n"
        "- If the evidence is insufficient to answer the question, clearly state that evidence is limited.\n"
        "- Keep explanations scientifically accurate, concise, and accessible."
    )

    def __init__(
        self,
        retriever: InvestigationRetriever,
        catalog: Any | None = None,
        llm_client: Optional[OllamaClient] = None,
        system_prompt: Optional[str] = None,
    ) -> None:
        self.retriever = retriever
        self.catalog = catalog
        self.llm_client = llm_client if llm_client is not None else OllamaClient()
        self.system_prompt = system_prompt or self.DEFAULT_SYSTEM_PROMPT

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def answer(
        self,
        question: str,
        conversation_history: Optional[List[Dict[str, str]]] = None,
        use_llm: bool = True,
    ) -> AssistantResponse:
        """
        Answer a research question using retrieved evidence and LLM generation.

        Parameters
        ----------
        question : str
            The user's query or follow-up question.
        conversation_history : list[dict[str, str]], optional
            Prior messages: [{'role': 'user'|'assistant', 'content': '...'}]
        use_llm : bool, default=True
            Whether to query Ollama (with automatic fallback to template synthesis).
        """
        if not question.strip():
            return AssistantResponse(
                question=question,
                answer="Please provide a research question.",
                confidence="insufficient_evidence",
                sources=[],
                retrieved_chunks=[],
                disclaimer="No question was provided.",
                llm_generated=False,
            )

        intent = _classify_question(question)
        results = self.retriever.hybrid_search(query=question, top_k=10)

        if not results:
            return self._insufficient(question)

        confidence = self._assess_confidence(results)
        if confidence == "insufficient_evidence":
            return self._insufficient(question)

        llm_success = False
        answer_text = ""
        validated_cites: List[str] = []
        rejected_cites: List[str] = []
        model_name: Optional[str] = None
        disclaimer_notes: List[str] = []

        if use_llm and self.llm_client:
            try:
                answer_text, validated_cites, rejected_cites = self._generate_llm_answer(
                    question=question,
                    results=results,
                    conversation_history=conversation_history,
                )
                llm_success = True
                model_name = self.llm_client.config.model
                if rejected_cites:
                    disclaimer_notes.append(
                        f"Notice: The model cited {', '.join(f'[{c}]' for c in rejected_cites)}, "
                        "which was not part of the retrieved evidence and was omitted from verified sources."
                    )
            except (OllamaConnectionError, OllamaTimeoutError, OllamaModelNotFoundError, OllamaClientError) as e:
                logger.warning("Ollama LLM generation unavailable (%s). Falling back to template synthesis.", e)
                disclaimer_notes.append(
                    f"[NOTICE]: Ollama LLM was unavailable ({e}). Fallback response synthesized using deterministic research templates."
                )
                answer_text = self._generate_answer(question, intent, results)
            except Exception as e:
                logger.error("Unexpected error during LLM generation: %s", e)
                disclaimer_notes.append(
                    f"[NOTICE]: LLM synthesis encountered an error ({e}). Fallback response generated."
                )
                answer_text = self._generate_answer(question, intent, results)
        else:
            answer_text = self._generate_answer(question, intent, results)

        # Build citations
        allowed_ids = set(validated_cites) if (llm_success and validated_cites) else None
        sources = self._build_citations(results, allowed_ids=allowed_ids)
        if not sources and results:
            sources = self._build_citations(results[:4])

        disclaimer: str | None = None
        if disclaimer_notes:
            disclaimer = " ".join(disclaimer_notes)
        elif confidence in ("low", "insufficient_evidence"):
            disclaimer = (
                "[NOTICE]: This answer is based on limited evidence. "
                "Please verify with original flight documentation."
            )

        return AssistantResponse(
            question=question,
            answer=answer_text,
            confidence=confidence,
            sources=sources,
            retrieved_chunks=results,
            disclaimer=disclaimer,
            llm_generated=llm_success,
            model_name=model_name,
            validated_citations=validated_cites,
            rejected_citations=rejected_cites,
        )

    def _generate_llm_answer(
        self,
        question: str,
        results: List[RetrievalResult],
        conversation_history: Optional[List[Dict[str, str]]] = None,
    ) -> Tuple[str, List[str], List[str]]:
        """
        Assemble research evidence, prompt Ollama, and validate generated citations.
        Returns: (answer_content, validated_citations, rejected_citations)
        """
        if not self.llm_client:
            raise OllamaClientError("Ollama client is not configured.")

        evidence_text = self._format_evidence_context(results)
        retrieved_ids = {r.chunk.investigation_id.upper() for r in results}

        system_instruction = (
            f"{self.system_prompt}\n\n"
            f"{evidence_text}\n\n"
            "INSTRUCTIONS FOR THIS TURN:\n"
            "- Answer the user's research question conversationally and thoroughly using only the research evidence above.\n"
            "- Cite supporting investigations using bracketed IDs (e.g. [BASS-II] or [ACME]).\n"
            "- If the provided research evidence does not contain the answer, explicitly state that the available evidence is insufficient."
        )

        messages: List[Dict[str, str]] = [{"role": "system", "content": system_instruction}]

        # Append bounded conversational history (up to last 6 messages)
        if conversation_history:
            recent_turns = conversation_history[-6:]
            for msg in recent_turns:
                role = msg.get("role", "user")
                content = msg.get("content", "")
                if role in ("user", "assistant") and content:
                    messages.append({"role": role, "content": content})

        messages.append({"role": "user", "content": question})

        resp = self.llm_client.chat(messages=messages)
        content = resp.get("content", "").strip()
        if not content:
            raise OllamaClientError("Ollama returned an empty response.")

        # Extract and validate citations
        extracted = self._extract_citations(content)
        catalog_ids = self._get_catalog_ids()
        validated, rejected = self._validate_citations(extracted, retrieved_ids, catalog_ids)

        return content, validated, rejected

    def _format_evidence_context(self, results: List[RetrievalResult], max_chunks: int = 6) -> str:
        """Format top retrieved chunks into structured, citeable evidence blocks."""
        lines = ["RESEARCH EVIDENCE FROM ORBITAL COMBUSTION INVESTIGATIONS:"]
        lines.append("=" * 65)
        for idx, r in enumerate(results[:max_chunks], start=1):
            inv_id = r.chunk.investigation_id
            title = r.chunk.metadata.get("title", inv_id)
            platform = r.chunk.metadata.get("platform", "Unknown")
            facility = r.chunk.metadata.get("facility", "N/A")
            doi = r.chunk.metadata.get("doi", "N/A")
            version = r.chunk.metadata.get("active_version", "N/A")
            chunk_type = r.chunk.chunk_type

            lines.append(f"[EVIDENCE {idx}] Investigation ID: [{inv_id}] | Title: {title}")
            lines.append(f"Platform: {platform} | Facility: {facility} | DOI: {doi} | Version: {version} | Section: {chunk_type}")
            lines.append(f"Content:\n{r.chunk.text.strip()}")
            lines.append("-" * 65)
        return "\n".join(lines)

    @staticmethod
    def _extract_citations(text: str) -> List[str]:
        """Extract investigation IDs cited in brackets like [BASS-II] or [SAME]."""
        bracket_matches = re.findall(r"\[([A-Za-z0-9_\-]+)\]", text)
        return list(dict.fromkeys(m.upper() for m in bracket_matches if not m.lower().startswith("evidence")))

    def _validate_citations(
        self,
        citations: List[str],
        retrieved_inv_ids: Set[str],
        catalog_ids: Set[str],
    ) -> Tuple[List[str], List[str]]:
        """Separate citations into validated (present in evidence) and rejected."""
        validated: List[str] = []
        rejected: List[str] = []
        for c in citations:
            c_upper = c.upper()
            if c_upper in retrieved_inv_ids:
                validated.append(c_upper)
            else:
                # If it's an investigation id or looks like one, but wasn't in retrieved evidence
                rejected.append(c_upper)
        return validated, rejected

    def _get_catalog_ids(self) -> Set[str]:
        """Collect all canonical investigation IDs present in catalog."""
        if self.catalog is not None:
            if hasattr(self.catalog, "list_all"):
                return {inv.id.upper() for inv in self.catalog.list_all()}
            if hasattr(self.catalog, "investigations"):
                return {inv["id"].upper() for inv in self.catalog.investigations}
        return set()

    # ------------------------------------------------------------------
    # Deterministic Answer Generation (Template-based fallback)
    # ------------------------------------------------------------------

    def _generate_answer(
        self,
        question: str,
        intent: str,
        results: list[RetrievalResult],
    ) -> str:
        """Produce a human-readable answer from the retrieved chunks."""
        if intent == "definition":
            return self._answer_definition(question, results)
        if intent == "how":
            return self._answer_how(question, results)
        if intent == "why":
            return self._answer_why(question, results)
        if intent == "who":
            return self._answer_who(question, results)
        if intent in ("list", "summary"):
            return self._answer_list(question, results)
        if intent == "comparison":
            return self._answer_comparison(question, results)
        if intent == "gap":
            return self._answer_gap(question, results)
        return self._answer_general(question, results)

    def _answer_definition(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        desc_chunks = [
            r for r in results if r.chunk.chunk_type == "description"
        ]
        source_chunks = desc_chunks[:3] if desc_chunks else results[:3]

        lines = [f"Based on orbital combustion research data:\n"]
        for r in source_chunks:
            title = r.chunk.metadata.get("title", r.chunk.investigation_id)
            lines.append(f"• **[{r.chunk.investigation_id}] {title}**: {self._truncate(r.chunk.text, 220)}")
        return "\n".join(lines)

    def _answer_how(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        preferred = [
            r
            for r in results
            if r.chunk.chunk_type in ("objective", "application", "description")
        ]
        source_chunks = preferred[:4] if preferred else results[:4]

        lines = ["Here is how this is addressed in flight research:\n"]
        for i, r in enumerate(source_chunks, 1):
            title = r.chunk.metadata.get("title", r.chunk.investigation_id)
            lines.append(
                f"{i}. **[{r.chunk.investigation_id}] {title}** ({r.chunk.chunk_type}): "
                f"{self._truncate(r.chunk.text, 200)}"
            )
        return "\n".join(lines)

    def _answer_why(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        preferred = [
            r
            for r in results
            if r.chunk.chunk_type in ("objective", "context", "description")
        ]
        source_chunks = preferred[:3] if preferred else results[:3]

        lines = ["Investigated for the following scientific reasons:\n"]
        for r in source_chunks:
            title = r.chunk.metadata.get("title", r.chunk.investigation_id)
            lines.append(
                f"• **[{r.chunk.investigation_id}] {title}**: {self._truncate(r.chunk.text, 220)}"
            )
        return "\n".join(lines)

    def _answer_who(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        lines = ["Relevant investigators and research teams in flight records:\n"]
        seen_invs: set[str] = set()
        for r in results:
            inv_id = r.chunk.investigation_id
            if inv_id in seen_invs:
                continue
            seen_invs.add(inv_id)
            inv = self._get_investigation(inv_id)
            investigators = inv.get("investigators", [])
            title = inv.get("title", inv_id)
            if investigators:
                names = [
                    inv_person.get("name", str(inv_person))
                    if isinstance(inv_person, dict)
                    else getattr(inv_person, "name", str(inv_person))
                    for inv_person in investigators
                ]
                lines.append(f"• **[{inv_id}] {title}**: {', '.join(names)}")
            else:
                lines.append(
                    f"• **[{inv_id}] {title}**: Investigator details not specified."
                )
            if len(seen_invs) >= 4:
                break
        return "\n".join(lines)

    def _answer_list(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        seen: set[str] = set()
        lines = ["Relevant flight investigations identified:\n"]
        for r in results:
            inv_id = r.chunk.investigation_id
            if inv_id in seen:
                continue
            seen.add(inv_id)
            inv = self._get_investigation(inv_id)
            title = inv.get("title", inv_id)
            cats = inv.get("categories", [inv.get("category", "")])
            if isinstance(cats, str):
                cats = [cats]
            cats_str = ", ".join(str(c).replace("_", " ") for c in cats if c)
            lines.append(f"• **[{inv_id}] {title}** — Categories: {cats_str}")
            if len(seen) >= 6:
                break
        return "\n".join(lines)

    def _answer_comparison(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        inv_ids = list(dict.fromkeys(r.chunk.investigation_id for r in results))
        if len(inv_ids) >= 2:
            comp = self.compare_investigations(inv_ids[0], inv_ids[1])
            title1 = comp.investigation_1.get("title", inv_ids[0])
            title2 = comp.investigation_2.get("title", inv_ids[1])
            lines = [
                f"Comparing **[{inv_ids[0]}] {title1}** vs **[{inv_ids[1]}] {title2}**:\n",
                f"• **Similarities**: {'; '.join(comp.similarities[:2])}",
                f"• **Differences**: {'; '.join(comp.differences[:2])}",
            ]
            if comp.shared_categories:
                lines.append(
                    f"• **Shared Categories**: {', '.join(comp.shared_categories)}"
                )
            lines.append(f"\n_{comp.recommendation}_")
            return "\n".join(lines)

        return self._answer_general(question, results)

    def _answer_gap(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        gap_analysis = self.find_research_gaps(question)
        lines = [
            f"Research coverage and potential gaps for '{question}':\n",
            f"• **Covered areas**: {', '.join(gap_analysis.covered_areas[:6])}",
            f"• **Identified gaps**: {'; '.join(gap_analysis.potential_gaps[:3])}",
        ]
        if gap_analysis.suggested_research_directions:
            lines.append(
                f"• **Suggested directions**: "
                f"{'; '.join(gap_analysis.suggested_research_directions[:2])}"
            )
        return "\n".join(lines)

    def _answer_general(
        self, question: str, results: list[RetrievalResult]
    ) -> str:
        lines = ["Summary based on indexed microgravity combustion evidence:\n"]
        seen: set[str] = set()
        for r in results[:5]:
            inv_id = r.chunk.investigation_id
            if inv_id in seen:
                continue
            seen.add(inv_id)
            title = r.chunk.metadata.get("title", inv_id)
            lines.append(
                f"• **[{inv_id}] {title}** ({r.chunk.chunk_type}, score: "
                f"{r.score:.2f}): {self._truncate(r.chunk.text, 180)}"
            )

        if len(results) > 5:
            lines.append(
                f"\n_({len(results) - 5} additional results available.)_"
            )
        return "\n".join(lines)

    # ------------------------------------------------------------------
    # Confidence assessment
    # ------------------------------------------------------------------

    def _assess_confidence(self, results: list[RetrievalResult]) -> str:
        """Determine confidence from retrieval scores and result count."""
        if not results:
            return "insufficient_evidence"
        top_score = results[0].score
        n_good = sum(1 for r in results if r.score >= self._MEDIUM_THRESHOLD)

        if top_score >= self._HIGH_THRESHOLD and n_good >= 3:
            return "high"
        if top_score >= self._MEDIUM_THRESHOLD and n_good >= 1:
            return "medium"
        if top_score > 0:
            return "low"
        return "insufficient_evidence"

    # ------------------------------------------------------------------
    # Citation builder
    # ------------------------------------------------------------------

    def _build_citations(
        self,
        results: list[RetrievalResult],
        allowed_ids: Optional[Set[str]] = None,
    ) -> list[SourceCitation]:
        """De-duplicate and build source citations with full attribution metadata."""
        seen: set[str] = set()
        citations: list[SourceCitation] = []
        for r in results:
            inv_id = r.chunk.investigation_id
            if allowed_ids is not None and inv_id.upper() not in allowed_ids:
                continue
            if inv_id in seen:
                continue
            seen.add(inv_id)
            title = r.chunk.metadata.get("title", inv_id)
            url = r.chunk.metadata.get("url")
            doi = r.chunk.metadata.get("doi")
            version = r.chunk.metadata.get("active_version")
            chunk_type = r.chunk.chunk_type

            if not url and doi:
                url = f"https://doi.org/{doi}"

            citations.append(
                SourceCitation(
                    investigation_id=inv_id,
                    title=str(title),
                    relevant_text=self._truncate(r.chunk.text, 220),
                    url=url,
                    doi=doi,
                    active_version=version,
                    source_field=chunk_type,
                )
            )
        return citations

    # ------------------------------------------------------------------
    # Comparison & Domain Analysis helpers
    # ------------------------------------------------------------------

    def compare_investigations(self, id1: str, id2: str) -> ComparisonResponse:
        """Compare two investigations side by side."""
        inv1 = self._get_investigation(id1)
        inv2 = self._get_investigation(id2)

        cats1 = self._extract_categories(inv1)
        cats2 = self._extract_categories(inv2)
        shared = sorted(cats1 & cats2)
        unique1 = sorted(cats1 - cats2)
        unique2 = sorted(cats2 - cats1)

        similarities = self._find_similarities(inv1, inv2)
        differences = self._find_differences(inv1, inv2)

        recommendation = self._comparison_recommendation(
            inv1, inv2, shared, similarities, differences
        )

        return ComparisonResponse(
            investigation_1=inv1,
            investigation_2=inv2,
            similarities=similarities,
            differences=differences,
            shared_categories=shared,
            unique_categories_1=unique1,
            unique_categories_2=unique2,
            recommendation=recommendation,
        )

    def summarize_category(self, category: str) -> CategorySummary:
        """Summarise all research in a given category."""
        investigations = self._investigations_for_category(category)

        inv_ids = [self._inv_id(inv) for inv in investigations]
        objectives = self._collect_field(investigations, "objective", "objectives", "research_objectives")
        platforms = self._collect_field(investigations, "platform")

        summary_text = self._build_category_summary(category, investigations)

        return CategorySummary(
            category=category,
            investigation_count=len(investigations),
            investigations=inv_ids,
            key_objectives=objectives[:20],
            platforms_used=sorted(set(platforms)),
            summary_text=summary_text,
        )

    def find_research_gaps(self, topic: str) -> GapAnalysis:
        """Identify potential research gaps in a topic area."""
        results = self.retriever.hybrid_search(query=topic, top_k=20)
        covered = self._extract_covered_areas(results)
        related_ids = list(
            dict.fromkeys(r.chunk.investigation_id for r in results)
        )

        potential_gaps = self._infer_gaps(topic, covered)
        suggestions = self._suggest_directions(topic, potential_gaps)

        return GapAnalysis(
            topic=topic,
            covered_areas=covered,
            potential_gaps=potential_gaps,
            suggested_research_directions=suggestions,
            related_investigations=related_ids[:15],
        )

    def _get_investigation(self, inv_id: str) -> dict[str, Any]:
        """Retrieve the full investigation dict from the catalog or chunks."""
        if self.catalog is not None:
            getter = getattr(self.catalog, "get", None)
            if callable(getter):
                inv = getter(inv_id)
                if inv is not None:
                    return inv if isinstance(inv, dict) else (
                        inv.model_dump() if hasattr(inv, "model_dump") else dict(inv)
                    )

        chunks = self.retriever.retrieve_by_investigation(inv_id)
        if not chunks:
            return {"id": inv_id, "title": inv_id}

        inv_dict: dict[str, Any] = {"id": inv_id}
        inv_dict.update(chunks[0].metadata)
        for chunk in chunks:
            inv_dict.setdefault(chunk.chunk_type, chunk.text)
        return inv_dict

    def _investigations_for_category(self, category: str) -> list[dict[str, Any]]:
        """Return investigations matching *category* from catalog or chunks."""
        results: list[dict[str, Any]] = []
        cat_lower = category.lower()

        if self.catalog is not None:
            all_invs = getattr(self.catalog, "investigations", None)
            if all_invs is None:
                all_invs_func = getattr(self.catalog, "all", None)
                if callable(all_invs_func):
                    all_invs = all_invs_func()
                elif hasattr(self.catalog, "list_all"):
                    all_invs = self.catalog.list_all()
            if all_invs:
                for inv in all_invs:
                    inv_dict = inv if isinstance(inv, dict) else (
                        inv.model_dump() if hasattr(inv, "model_dump") else dict(inv)
                    )
                    cats = inv_dict.get("categories", [inv_dict.get("category", "")])
                    if isinstance(cats, str):
                        cats = [cats]
                    if any(cat_lower in str(c).lower() for c in cats):
                        results.append(inv_dict)
                return results

        seen: set[str] = set()
        for chunk in self.retriever.chunks:
            if chunk.investigation_id in seen:
                continue
            cats = chunk.metadata.get("categories", [chunk.metadata.get("category", "")])
            if isinstance(cats, str):
                cats = [cats]
            if any(cat_lower in str(c).lower() for c in cats):
                seen.add(chunk.investigation_id)
                inv = {"id": chunk.investigation_id}
                inv.update(chunk.metadata)
                results.append(inv)
        return results

    @staticmethod
    def _inv_id(inv: dict[str, Any]) -> str:
        return str(inv.get("id", inv.get("investigation_id", "unknown")))

    @staticmethod
    def _extract_categories(inv: dict[str, Any]) -> set[str]:
        cats = inv.get("categories", [inv.get("category", "")])
        if isinstance(cats, str):
            cats = [cats]
        return {str(c).strip().lower() for c in cats if c}

    def _find_similarities(
        self, inv1: dict[str, Any], inv2: dict[str, Any]
    ) -> list[str]:
        sims: list[str] = []
        shared_cats = self._extract_categories(inv1) & self._extract_categories(inv2)
        if shared_cats:
            sims.append(f"Both belong to categories: {', '.join(sorted(shared_cats))}")

        p1 = str(inv1.get("platform", "")).lower()
        p2 = str(inv2.get("platform", "")).lower()
        if p1 and p1 == p2:
            sims.append(f"Both use platform: {inv1.get('platform')}")

        s1 = str(inv1.get("status", "")).lower()
        s2 = str(inv2.get("status", "")).lower()
        if s1 and s1 == s2:
            sims.append(f"Both have status: {inv1.get('status')}")

        kw1 = self._extract_keywords(str(inv1.get("description", "")))
        kw2 = self._extract_keywords(str(inv2.get("description", "")))
        shared_kw = kw1 & kw2
        if shared_kw:
            sims.append(f"Shared research keywords: {', '.join(sorted(shared_kw)[:8])}")

        if not sims:
            sims.append("No strong surface-level similarities detected.")
        return sims

    def _find_differences(
        self, inv1: dict[str, Any], inv2: dict[str, Any]
    ) -> list[str]:
        diffs: list[str] = []
        title1 = inv1.get("title", "Investigation 1")
        title2 = inv2.get("title", "Investigation 2")

        p1 = inv1.get("platform", "N/A")
        p2 = inv2.get("platform", "N/A")
        if str(p1).lower() != str(p2).lower():
            diffs.append(f"Platform: {title1} uses '{p1}' vs {title2} uses '{p2}'")

        s1 = inv1.get("status", "N/A")
        s2 = inv2.get("status", "N/A")
        if str(s1).lower() != str(s2).lower():
            diffs.append(f"Status: {title1} is '{s1}' vs {title2} is '{s2}'")

        cats1 = self._extract_categories(inv1)
        cats2 = self._extract_categories(inv2)
        only1 = cats1 - cats2
        only2 = cats2 - cats1
        if only1:
            diffs.append(f"Unique to {title1}: categories {', '.join(sorted(only1))}")
        if only2:
            diffs.append(f"Unique to {title2}: categories {', '.join(sorted(only2))}")

        if not diffs:
            diffs.append("No major structural differences detected.")
        return diffs

    def _comparison_recommendation(
        self,
        inv1: dict[str, Any],
        inv2: dict[str, Any],
        shared_cats: list[str],
        similarities: list[str],
        differences: list[str],
    ) -> str:
        title1 = inv1.get("title", inv1.get("id", "Investigation 1"))
        title2 = inv2.get("title", inv2.get("id", "Investigation 2"))
        n_sim = len(similarities)
        n_diff = len(differences)

        if n_sim > n_diff:
            return (
                f"'{title1}' and '{title2}' are closely related with "
                f"{len(shared_cats)} shared categories. Consider reviewing "
                "them together for a comprehensive understanding of the topic."
            )
        if n_diff > n_sim:
            return (
                f"'{title1}' and '{title2}' take different approaches. "
                "They may offer complementary perspectives on the research area."
            )
        return (
            f"'{title1}' and '{title2}' have a balanced mix of overlaps "
            "and distinctions. Reviewing both will provide breadth and depth."
        )

    @staticmethod
    def _collect_field(
        investigations: list[dict[str, Any]], *field_names: str
    ) -> list[str]:
        values: list[str] = []
        seen: set[str] = set()
        for inv in investigations:
            for fn in field_names:
                val = inv.get(fn)
                if val is None:
                    continue
                if isinstance(val, list):
                    for v in val:
                        s = str(v).strip()
                        if s and s.lower() not in seen:
                            seen.add(s.lower())
                            values.append(s)
                else:
                    s = str(val).strip()
                    if s and s.lower() not in seen:
                        seen.add(s.lower())
                        values.append(s)
        return values

    def _build_category_summary(
        self, category: str, investigations: list[dict[str, Any]]
    ) -> str:
        n = len(investigations)
        if n == 0:
            return f"No investigations found for category '{category}'."

        titles = [inv.get("title", inv.get("id", "Untitled")) for inv in investigations[:5]]
        titles_str = ", ".join(f"'{t}'" for t in titles)
        extra = f" (and {n - 5} more)" if n > 5 else ""

        platforms = set()
        for inv in investigations:
            p = inv.get("platform")
            if p:
                platforms.add(str(p))
        platform_str = (
            f" Platforms used include: {', '.join(sorted(platforms))}."
            if platforms
            else ""
        )

        return (
            f"The '{category}' category contains {n} investigation(s) "
            f"including {titles_str}{extra}.{platform_str} "
            f"These investigations collectively advance our understanding "
            f"of {category.lower()} phenomena in combustion research."
        )

    def _extract_covered_areas(
        self, results: list[RetrievalResult]
    ) -> list[str]:
        keyword_counts: Counter[str] = Counter()
        for r in results:
            for kw in self._extract_keywords(r.chunk.text):
                keyword_counts[kw] += 1
        return [kw for kw, _ in keyword_counts.most_common(15)]

    def _infer_gaps(self, topic: str, covered: list[str]) -> list[str]:
        common_subtopics = self._related_subtopics(topic)
        covered_lower = {c.lower() for c in covered}
        gaps: list[str] = []
        for sub in common_subtopics:
            if not any(sub.lower() in c for c in covered_lower):
                gaps.append(sub)
        if not gaps:
            gaps.append(
                f"No obvious gaps detected — '{topic}' appears well covered."
            )
        return gaps

    def _suggest_directions(
        self, topic: str, gaps: list[str]
    ) -> list[str]:
        suggestions: list[str] = []
        for gap in gaps[:5]:
            if gap.startswith("No obvious gaps"):
                suggestions.append(
                    f"Consider deeper quantitative studies on '{topic}'."
                )
            else:
                suggestions.append(
                    f"Investigate '{gap}' in the context of {topic}."
                )
        if not suggestions:
            suggestions.append(
                f"Extend current {topic} research to new microgravity platforms."
            )
        return suggestions

